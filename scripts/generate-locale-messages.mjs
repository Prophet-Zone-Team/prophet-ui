function deepTranslate(obj, map) {
  const result = {};

  for (const [key, value] of Object.entries(obj)) {
    if (typeof value === "object" && value !== null) {
      result[key] = deepTranslate(value, map[key] ?? {});
      continue;
    }

    result[key] = map[key] ?? value;
  }

  return result;
}

